<script>
document.addEventListener('DOMContentLoaded', function () {

    var successBox = document.getElementById('ls-success');
    var errorBox   = document.getElementById('ls-error');

    function showMsg(box, msg) {
        if (!box) return;
        box.innerHTML = msg;
        box.style.transition = '';
        box.style.opacity = 1;
        box.style.display = 'block';
    }

    function fadeOutMsgs() {
        [successBox, errorBox].forEach(function (box) {
            if (!box || box.style.display === 'none') return;
            box.style.transition = 'opacity 400ms';
            box.style.opacity = 0;
            setTimeout(function () { box.style.display = 'none'; }, 400);
        });
    }

    // Custom request form submit
    var form = document.getElementById('pcat_custom_request');
    if (form) {
        form.addEventListener('submit', function (e) {
            e.preventDefault();

            var submitBtn = form.querySelector('button[type="submit"]');
            if (submitBtn) {
                submitBtn.disabled = true;
                submitBtn.insertAdjacentHTML('beforeend',
                    '<span class="spinner-border spinner-border-sm me-2 ls-spinner" role="status" aria-hidden="true"></span>');
            }

            function resetBtn() {
                if (!submitBtn) return;
                submitBtn.disabled = false;
                var sp = submitBtn.querySelector('.ls-spinner');
                if (sp) sp.remove();
            }

            fetch("<?php echo esc_url( rest_url( 'ls/v1/custom-setting-request' ) ); ?>", {
                method: 'POST',
                body: new FormData(form)
            })
            .then(function (res) {
                return res.json().catch(function () { return {}; }).then(function (data) {
                    return { ok: res.ok, data: data };
                });
            })
            .then(function (r) {
                var response = r.data;
                console.log('API Response:', response);

                if (!r.ok) {
                    showMsg(errorBox, response.error || 'An error occurred. Please try again.');
                } else if (response.success) {
                    showMsg(successBox, response.success);
                    form.reset();
                    var prev = document.querySelector('.lsimgprev');
                    if (prev) prev.innerHTML = '';
                } else if (response.error) {
                    showMsg(errorBox, response.error);
                } else {
                    showMsg(errorBox, 'An unexpected response was received.');
                }
            })
            .catch(function () {
                showMsg(errorBox, 'An error occurred. Please try again.');
            })
            .finally(function () {
                resetBtn();
                setTimeout(fadeOutMsgs, 5000);
            });
        });
    }

    // Image preview on file select
    document.querySelectorAll('.ls_fileupld').forEach(function (input) {
        input.addEventListener('change', function (e) {
            var preview = document.querySelector('.lsimgprev');
            if (!preview) return;
            preview.innerHTML = '';

            Array.prototype.forEach.call(e.target.files, function (file) {
                if (!file.type.startsWith('image/')) return;
                var url = URL.createObjectURL(file);
                preview.insertAdjacentHTML('beforeend',
                    '<span class="pip">' +
                        '<img class="imageThumb" src="' + url + '" />' +
                        '<span class="remove">×</span>' +
                    '</span>');
            });
        });
    });

    // Remove preview thumbnail
    document.addEventListener('click', function (e) {
        var removeBtn = e.target.closest('.lsimgprev .remove');
        if (removeBtn) {
            var pip = removeBtn.closest('.pip');
            if (pip) pip.remove();
        }
    });

});
</script>


